VARIATION_SELECTORS = "\ufe0f\ufe0e\u200d"
SKIN_TONES = "".join(chr(c) for c in range(0x1F3FB, 0x1F400))
REGIONAL_BASE = 0x1F1E6

_TEXT_EMOJI_RE = re.compile(
    "(?<![\\w:;=])(" + "|".join(re.escape(k) for k in
                                sorted(TEXT_EMOJI, key=len, reverse=True)) + ")(?!\\w)")


def to_text(text: str) -> str:
    """Готовит строку для телефона: эмодзи → коды смайлов Jimm.

    Коды отделяются пробелами (так же поступает сам клиент, вставляя смайл
    из меню), а идущие подряд одинаковые схлопываются в один.
    """
    if not text:
        return text

    out: list[str] = []
    last_emoji: str | None = None

    def put_emoji(token: str) -> None:
        nonlocal last_emoji
        if last_emoji == token:
            return
        if out and not out[-1].endswith((" ", "\n", "\t")):
            out.append(" ")
        out.append(token)
        last_emoji = token

    def put_char(ch: str) -> None:
        nonlocal last_emoji
        if last_emoji is not None and not ch.isspace() and ch not in ".,!?:;)":
            out.append(" ")
        out.append(ch)
        last_emoji = None

    chars = [c for c in text if c not in VARIATION_SELECTORS and c not in SKIN_TONES]
    i = 0
    while i < len(chars):
        ch = chars[i]
        # Флаги: пара региональных индикаторов даёт код страны
        if REGIONAL_BASE <= ord(ch) <= REGIONAL_BASE + 25 and i + 1 < len(chars):
            nxt = chars[i + 1]
            if REGIONAL_BASE <= ord(nxt) <= REGIONAL_BASE + 25:
                put_emoji("[%s%s]" % (chr(ord(ch) - REGIONAL_BASE + 65),
                                      chr(ord(nxt) - REGIONAL_BASE + 65)))
                i += 2
                continue
        replacement = EMOJI_TEXT.get(ch)
        if replacement is not None:
            put_emoji(replacement)
        elif ord(ch) > 0xFFFF or _is_symbol(ch):
            put_emoji(_name_of(ch))
        else:
            put_char(ch)
        i += 1
    return "".join(out)


def to_emoji(text: str) -> str:
    """Обратный перевод для сообщений с телефона."""
    if not text:
        return text
    return _TEXT_EMOJI_RE.sub(lambda m: TEXT_EMOJI[m.group(1)], text)


def _is_symbol(ch: str) -> bool:
    """Символы-картинки из базовой плоскости, которых нет на старом экране."""
    return unicodedata.category(ch) == "So" and ord(ch) > 0x2100


def _name_of(ch: str) -> str:
    try:
        name = unicodedata.name(ch).lower()
    except ValueError:
        return "?"
    for prefix in ("emoji ", "face with ", "smiling face with "):
        if name.startswith(prefix):
            name = name[len(prefix):]
    return "[%s]" % name
